import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:cloud_functions/cloud_functions.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'room_screen.dart';

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  if (FirebaseAuth.instance.currentUser == null) {
    await FirebaseAuth.instance.signInAnonymously();
  }
  runApp(const GolfApp());
}

class GolfApp extends StatelessWidget {
  const GolfApp({super.key});
  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Golf Starter',
      theme: ThemeData(useMaterial3: true),
      home: const HomeScreen(),
    );
  }
}

class HomeScreen extends StatefulWidget {
  const HomeScreen({super.key});
  @override
  State<HomeScreen> createState() => _HomeScreenState();
}

class _HomeScreenState extends State<HomeScreen> {
  final _roomCtrl = TextEditingController();
  final _cf = FirebaseFunctions.instance;
  String? _error;

  Future<void> _createRoom() async {
    try {
      setState(() { _error = null; });
      final res = await _cf.httpsCallable('createRoom').call({'maxPlayers': 4});
      final roomId = res.data['roomId'];
      if (mounted) {
        Navigator.of(context).push(MaterialPageRoute(builder: (_) => RoomScreen(roomId: roomId)));
      }
    } catch (e) { setState(() { _error = 'Error: $e'; }); }
  }

  Future<void> _joinRoom() async {
    try {
      setState(() { _error = null; });
      final roomIdentifier = _roomCtrl.text.trim();
      final res = await _cf.httpsCallable('joinRoom').call({'roomIdentifier': roomIdentifier});
      final roomId = res.data['roomId'];
      if (mounted) {
        Navigator.of(context).push(MaterialPageRoute(builder: (_) => RoomScreen(roomId: roomId)));
      }
    } catch (e) { setState(() { _error = 'Error: $e'; }); }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Golf — Starter')),
      body: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            ElevatedButton(onPressed: _createRoom, child: const Text('Create Room (callable)')),
            const SizedBox(height: 12),
            TextField(controller: _roomCtrl, decoration: const InputDecoration(labelText: 'Room ID or Invite Code')),
            const SizedBox(height: 8),
            ElevatedButton(onPressed: _joinRoom, child: const Text('Join Room (callable)')),
            const SizedBox(height: 16),
            if (_error != null) Text(_error!, style: const TextStyle(color: Colors.red)),
          ],
        ),
      ),
    );
  }
}
