import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:cloud_functions/cloud_functions.dart';
import 'package:cloud_firestore/cloud_firestore.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  if (FirebaseAuth.instance.currentUser == null) {
    await FirebaseAuth.instance.signInAnonymously();
  }
  runApp(const GolfApp());
}

class GolfApp extends StatelessWidget {
  const GolfApp({super.key});
  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Golf Starter',
      theme: ThemeData(useMaterial3: true),
      home: const HomeScreen(),
    );
  }
}

class HomeScreen extends StatefulWidget {
  const HomeScreen({super.key});
  @override
  State<HomeScreen> createState() => _HomeScreenState();
}

class _HomeScreenState extends State<HomeScreen> {
  final _roomCtrl = TextEditingController();
  final _cf = FirebaseFunctions.instance;
  String? _roomId;
  String? _error;

  Future<void> _createRoom() async {
    try {
      final res = await _cf.httpsCallable('createRoom').call({'maxPlayers': 4});
      setState(() {
        _roomId = res.data['roomId'];
        _error = null;
      });
    } catch (e) {
      setState(() { _error = 'Error: $e'; });
    }
  }

  Future<void> _joinRoom() async {
    final id = _roomCtrl.text.trim();
    if (id.isEmpty) return;
    try {
      await _cf.httpsCallable('joinRoom').call({'roomId': id});
      setState(() {
        _roomId = id;
        _error = null;
      });
    } catch (e) {
      setState(() { _error = 'Error: $e'; });
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Golf — Starter')),
      body: _roomId == null ? _buildLobby() : GameScreen(roomId: _roomId!),
    );
  }

  Widget _buildLobby() {
    return Padding(
      padding: const EdgeInsets.all(16),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          ElevatedButton(onPressed: _createRoom, child: const Text('Create Room')),
          const SizedBox(height: 12),
          TextField(controller: _roomCtrl, decoration: const InputDecoration(labelText: 'Room ID')),
          const SizedBox(height: 8),
          ElevatedButton(onPressed: _joinRoom, child: const Text('Join Room')),
          if (_error != null) ...[
            const SizedBox(height: 16),
            Text(_error!, style: const TextStyle(color: Colors.red)),
          ]
        ],
      ),
    );
  }
}

class GameScreen extends StatelessWidget {
  final String roomId;
  GameScreen({super.key, required this.roomId});

  final _cf = FirebaseFunctions.instance;
  final _auth = FirebaseAuth.instance;

  @override
  Widget build(BuildContext context) {
    return StreamBuilder(
      stream: FirebaseFirestore.instance.collection('rooms').doc(roomId).snapshots(),
      builder: (context, snapshot) {
        if (!snapshot.hasData) return const Center(child: CircularProgressIndicator());
        final room = snapshot.data!.data()!;
        final players = (room['players'] as List).map((p) => p['uid']).toList();
        final me = players.firstWhere((p) => p == _auth.currentUser!.uid, orElse: () => null);

        return Padding(
          padding: const EdgeInsets.all(16),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Text('Room: $roomId', style: Theme.of(context).textTheme.headlineSmall),
              const SizedBox(height: 8),
              Text('Status: ${room['status']}'),
              const SizedBox(height: 8),
              Wrap(spacing: 8, children: [
                if (room['status'] == 'waiting') ...[
                  ElevatedButton(
                    onPressed: () => _cf.httpsCallable('setReady').call({'roomId': roomId, 'ready': true}),
                    child: const Text('Ready'),
                  ),
                  if (room['ownerUid'] == me)
                    ElevatedButton(
                      onPressed: () => _cf.httpsCallable('startGame').call({'roomId': roomId}),
                      child: const Text('Start Game'),
                    ),
                ],
                if (room['status'] == 'playing' && room['turn'] == players.indexOf(me)) ...[
                  ElevatedButton(
                    onPressed: () => _cf.httpsCallable('drawFromDeck').call({'roomId': roomId}),
                    child: const Text('Draw from Deck'),
                  ),
                  ElevatedButton(
                    onPressed: () => _cf.httpsCallable('drawFromDiscard').call({'roomId': roomId}),
                    child: const Text('Draw from Discard'),
                  ),
                  ElevatedButton(
                    onPressed: () => _cf.httpsCallable('endTurn').call({'roomId': roomId}),
                    child: const Text('End Turn'),
                  ),
                ]
              ]),
              const SizedBox(height: 16),
              Text('Players:', style: Theme.of(context).textTheme.titleLarge),
              ...players.map((p) => Text(p)),
              const SizedBox(height: 16),
              if (room['status'] == 'playing') ...[
                Text('Discard: ${room['discard'].join(', ')}'),
                const SizedBox(height: 16),
                Text('Your Hand:', style: Theme.of(context).textTheme.titleLarge),
                Wrap(
                  spacing: 8,
                  children: (room['hands'][players.indexOf(me)] as List)
                      .map((card) => ElevatedButton(
                            onPressed: () => _cf.httpsCallable('discardCard').call({'roomId': roomId, 'card': card}),
                            child: Text(card),
                          ))
                      .toList(),
                ),
              ]
            ],
          ),
        );
      },
    );
  }
}
