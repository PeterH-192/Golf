import 'dart:convert';
import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:http/http.dart' as http;
import 'firebase_options.dart'; // generated by `flutterfire configure`

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  if (FirebaseAuth.instance.currentUser == null) {
    await FirebaseAuth.instance.signInAnonymously();
  }
  runApp(const GolfApp());
}

class GolfApp extends StatelessWidget {
  const GolfApp({super.key});
  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Golf Starter',
      theme: ThemeData(useMaterial3: true),
      home: const HomeScreen(),
    );
  }
}

class HomeScreen extends StatefulWidget {
  const HomeScreen({super.key});
  @override
  State<HomeScreen> createState() => _HomeScreenState();
}

class _HomeScreenState extends State<HomeScreen> {
  final _roomCtrl = TextEditingController();
  String? _status;

  // Helper to get the base URL for cloud functions
  String get _functionsBaseUrl {
    // Default to us-central1, update if your functions are in a different region
    final region = 'us-central1';
    final projectId = Firebase.app().options.projectId;
    return 'https://$region-$projectId.cloudfunctions.net';
  }

  // Helper to make authenticated POST requests
  Future<Map<String, dynamic>> _post(String functionName, Map<String, dynamic> body) async {
    final user = FirebaseAuth.instance.currentUser;
    if (user == null) throw Exception('Not signed in');

    final token = await user.getIdToken();
    final url = Uri.parse('$_functionsBaseUrl/$functionName');

    final response = await http.post(
      url,
      headers: {
        'Content-Type': 'application/json',
        'Authorization': 'Bearer $token',
      },
      body: jsonEncode(body),
    );

    if (response.statusCode == 200) {
      // Our functions nest the actual response inside a 'data' property.
      return jsonDecode(response.body)['data'];
    } else {
      final errorBody = jsonDecode(response.body)['error'];
      throw Exception('Error ${response.statusCode}: ${errorBody['message']}');
    }
  }

  Future<void> _createRoom() async {
    try {
      final res = await _post('createRoom', {'maxPlayers': 4});
      setState(() { _status = "Room: ${res['roomId']} Invite: ${res['inviteCode']}"; });
    } catch (e) { setState(() { _status = 'Error: $e'; }); }
  }

  Future<void> _joinRoom() async {
    try {
      final id = _roomCtrl.text.trim();
      if (id.isEmpty) {
        setState(() { _status = 'Error: Room ID cannot be empty'; });
        return;
      }
      await _post('joinRoom', {'roomId': id});
      setState(() { _status = "Joined $id"; });
    } catch (e) { setState(() { _status = 'Error: $e'; }); }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Golf — Starter')),
      body: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            ElevatedButton(onPressed: _createRoom, child: const Text('Create Room (HTTP)')),
            const SizedBox(height: 12),
            TextField(controller: _roomCtrl, decoration: const InputDecoration(labelText: 'Room ID')),
            const SizedBox(height: 8),
            ElevatedButton(onPressed: _joinRoom, child: const Text('Join Room (HTTP)')),
            const SizedBox(height: 16),
            Text(_status ?? 'Status: idle'),
          ],
        ),
      ),
    );
  }
}
